#:package Microsoft.CodeAnalysis.CSharp@4.8.0

// Generates the interfaces of the client (issue #17) from the sources: IVimeo and one interface per section
// (IVimeoVideos for VimeoVideos, ...), with every public virtual method of the class, its XML documentation and its
// default values. Run it from the repository root after adding or changing a method:
//
//     dotnet run tools/GenerateInterfaces.cs
//
// It rewrites src/VimeoClient/Interfaces/*.cs. InterfaceTests checks that the interfaces match the classes.

using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

var root = Directory.GetCurrentDirectory();
var source = Path.Combine(root, "src", "VimeoClient");
var output = Path.Combine(source, "Interfaces");
Directory.CreateDirectory(output);

// The MIT header of the repository, taken from an existing file.
var headerLines = File.ReadAllLines(Path.Combine(source, "VimeoProperties.cs"));
var header = string.Join("\n", headerLines.TakeWhile(l => !l.StartsWith("namespace")).Select(l => l.TrimStart('﻿'))).TrimEnd() + "\n";

var files = Directory.GetFiles(Path.Combine(source, "Common"), "*.cs")
    .Concat(new[] { Path.Combine(source, "Vimeo.cs"), Path.Combine(source, "Vimeo.Async.cs") })
    .OrderBy(f => f, StringComparer.Ordinal)
    .ToList();

// The sections exposed by Vimeo (public virtual VimeoX Name => new VimeoX(this)).
var vimeoTree = CSharpSyntaxTree.ParseText(File.ReadAllText(Path.Combine(source, "Vimeo.cs")));
var sections = vimeoTree.GetRoot().DescendantNodes().OfType<PropertyDeclarationSyntax>()
    .Where(p => p.Modifiers.Any(SyntaxKind.PublicKeyword) && p.ExpressionBody?.Expression is ObjectCreationExpressionSyntax)
    .ToList();
var sectionTypes = new HashSet<string>(sections.Select(p => p.Type.ToString()), StringComparer.Ordinal);

// Class name -> (namespace, usings, methods)
var classes = new SortedDictionary<string, (string Namespace, SortedSet<string> Usings, List<MethodDeclarationSyntax> Methods)>(StringComparer.Ordinal);
foreach (var file in files)
{
    var tree = CSharpSyntaxTree.ParseText(File.ReadAllText(file));
    var unit = (CompilationUnitSyntax)tree.GetRoot();
    foreach (var ns in unit.Members.OfType<NamespaceDeclarationSyntax>())
    {
        var usings = ns.Usings.Concat(unit.Usings).Select(u => u.Name!.ToString());
        foreach (var type in ns.Members.OfType<ClassDeclarationSyntax>())
        {
            var name = type.Identifier.Text;
            if (name != "Vimeo" && !sectionTypes.Contains(name))
            {
                continue;
            }
            if (!classes.TryGetValue(name, out var entry))
            {
                entry = (ns.Name.ToString(), new SortedSet<string>(StringComparer.Ordinal), new List<MethodDeclarationSyntax>());
                classes[name] = entry;
            }
            foreach (var u in usings) entry.Usings.Add(u);
            entry.Methods.AddRange(type.Members.OfType<MethodDeclarationSyntax>().Where(m =>
                m.Modifiers.Any(SyntaxKind.PublicKeyword) && m.Modifiers.Any(SyntaxKind.VirtualKeyword)
                // RootAuthorization is the request builder of the implementation, not an operation of the API.
                && m.Identifier.Text != "RootAuthorization"));
        }
    }
}

var written = new List<string>();
foreach (var (className, (ns, usings, methods)) in classes)
{
    var interfaceName = "I" + className;
    var builder = new StringBuilder();
    builder.Append(header).Append('\n');
    builder.Append("// <auto-generated>\n//     Generated by tools/GenerateInterfaces.cs from the public virtual methods of ")
        .Append(className).Append(".\n//     Do not edit: run `dotnet run tools/GenerateInterfaces.cs` again.\n// </auto-generated>\n\n");
    builder.Append("namespace ").Append(ns).Append("\n{\n");
    var allUsings = new SortedSet<string>(usings, StringComparer.Ordinal);
    if (className == "Vimeo") allUsings.Add("Mafesoft.VimeoClient.Common");
    foreach (var u in allUsings) builder.Append("    using ").Append(u).Append(";\n");
    builder.Append('\n');

    var summary = className == "Vimeo"
        ? "The Vimeo client: the authentication methods and the sections of the API. Implemented by <see cref=\"Vimeo\"/>; mock it in the tests of the applications."
        : $"The operations of <see cref=\"{className}\"/>. Mock it in the tests of the applications.";
    builder.Append("    /// <summary>\n    /// ").Append(summary).Append("\n    /// </summary>\n");
    builder.Append("    public partial interface ").Append(interfaceName).Append("\n    {\n");

    if (className == "Vimeo")
    {
        builder.Append("        /// <summary>\n        /// The credentials and the settings of the client.\n        /// </summary>\n");
        builder.Append("        VimeoProperties Properties { get; }\n\n");
        foreach (var section in sections)
        {
            builder.Append("        /// <summary>\n        /// The section ").Append(section.Identifier.Text).Append(" (<see cref=\"").Append(section.Type).Append("\"/>).\n        /// </summary>\n");
            builder.Append("        I").Append(section.Type).Append(' ').Append(section.Identifier.Text).Append(" { get; }\n\n");
        }
    }

    foreach (var method in methods)
    {
        var doc = method.GetLeadingTrivia()
            .Where(t => t.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia))
            .Select(t => t.ToFullString())
            .LastOrDefault();
        if (doc != null)
        {
            foreach (var line in doc.Replace("\r", "").TrimEnd('\n').Split('\n'))
            {
                builder.Append("        ").Append(line.Trim()).Append('\n');
            }
        }

        builder.Append("        ")
            .Append(method.ReturnType.ToString()).Append(' ')
            .Append(method.Identifier.Text)
            .Append(method.TypeParameterList?.ToString() ?? string.Empty)
            .Append(method.ParameterList.ToString());
        foreach (var constraint in method.ConstraintClauses)
        {
            builder.Append(' ').Append(constraint.ToString());
        }
        builder.Append(";\n\n");
    }

    var body = builder.ToString().TrimEnd('\n') + "\n";
    body = body.Substring(0, body.Length - 1).TrimEnd() + "\n    }\n\n";

    // The class implements the interface; Vimeo returns the section classes, so its section properties are
    // implemented explicitly.
    builder.Clear().Append(body);
    builder.Append("    public partial class ").Append(className).Append(" : ").Append(interfaceName).Append("\n    {\n");
    if (className == "Vimeo")
    {
        foreach (var section in sections)
        {
            builder.Append("        I").Append(section.Type).Append(' ').Append(interfaceName).Append('.').Append(section.Identifier.Text)
                .Append(" => ").Append(section.Identifier.Text).Append(";\n");
        }
    }
    builder.Append("    }\n}\n");

    var path = Path.Combine(output, interfaceName + ".cs");
    File.WriteAllText(path, builder.ToString().Replace("\n", "\r\n"), new UTF8Encoding(false));
    written.Add(Path.GetFileName(path));
}

Console.WriteLine($"{written.Count} interfaces: {string.Join(", ", written)}");
