namespace VimeoClient.Model
{
    using System.Collections.Generic;
    using System.Text.Json;
    using System.Text.Json.Serialization;

    /// <summary>
    /// Transcript Metadata (Vimeo schema: transcript-metadata).
    /// </summary>
    public class TranscriptMetadata
    {
        /// <summary>
        /// Whether the transcript was automatically generated using AI.
        /// </summary>
        [JsonPropertyName("autogenerated")]
        public bool? Autogenerated { get; set; }

        /// <summary>
        /// The ID of the video.
        /// </summary>
        [JsonPropertyName("clip_id")]
        public long? ClipId { get; set; }

        /// <summary>
        /// The ID of the container.
        /// </summary>
        [JsonPropertyName("container_id")]
        public string ContainerId { get; set; }

        /// <summary>
        /// Whether the transcript has been marked as deleted.
        /// </summary>
        [JsonPropertyName("deleted")]
        public bool? Deleted { get; set; }

        /// <summary>
        /// Whether the transcript is enabled.
        /// </summary>
        [JsonPropertyName("enabled")]
        public bool? Enabled { get; set; }

        /// <summary>
        /// The ID of the transcript.
        /// </summary>
        [JsonPropertyName("id")]
        public string Id { get; set; }

        /// <summary>
        /// The kind of transcript. The value of this field can be `captions` for caption transcripts or `subtitles` for subtitle transcripts.
        /// </summary>
        [JsonPropertyName("kind")]
        public string Kind { get; set; }

        /// <summary>
        /// The language in which the transcript appears.
        /// </summary>
        [JsonPropertyName("language")]
        public string Language { get; set; }

        /// <summary>
        /// The total number of speakers in the transcript.
        /// </summary>
        [JsonPropertyName("speaker_count")]
        public long? SpeakerCount { get; set; }

        /// <summary>
        /// The ID of the text track.
        /// </summary>
        [JsonPropertyName("texttrack_id")]
        public long? TexttrackId { get; set; }

        /// <summary>
        /// The UUID of the transcript status.
        /// </summary>
        [JsonPropertyName("transcript_status_uuid")]
        public string TranscriptStatusUuid { get; set; }

        /// <summary>
        /// The total number of words in the transcript.
        /// </summary>
        [JsonPropertyName("word_count")]
        public long? WordCount { get; set; }

        /// <summary>
        /// The fields of the response not mapped by the library.
        /// </summary>
        [JsonExtensionData]
        public Dictionary<string, JsonElement> AdditionalData { get; set; }
    }
}
