namespace Mafesoft.VimeoClient.Model
{
    using System.Collections.Generic;
    using System.Text.Json;
    using System.Text.Json.Serialization;

    /// <summary>
    /// Segment (Vimeo schema: segment).
    /// </summary>
    public class TranscriptSegment
    {
        /// <summary>
        /// Whether the segment is autogenerated.
        /// </summary>
        [JsonPropertyName("autogenerated")]
        public bool? Autogenerated { get; set; }

        /// <summary>
        /// The cue end timestamp in milliseconds from the start of the video.
        /// </summary>
        [JsonPropertyName("cue_end")]
        public double? CueEnd { get; set; }

        /// <summary>
        /// The cue start timestamp in milliseconds from the start of the video.
        /// </summary>
        [JsonPropertyName("cue_start")]
        public double? CueStart { get; set; }

        /// <summary>
        /// Whether the segment is enabled.
        /// </summary>
        [JsonPropertyName("enabled")]
        public bool? Enabled { get; set; }

        /// <summary>
        /// The segment identifier.
        /// </summary>
        [JsonPropertyName("id")]
        public string Id { get; set; }

        /// <summary>
        /// The type of caption that the segment originates from.
        /// </summary>
        [JsonPropertyName("kind")]
        public string Kind { get; set; }

        /// <summary>
        /// The language of the segment.
        /// </summary>
        [JsonPropertyName("language")]
        public string Language { get; set; }

        /// <summary>
        /// The line data for the segment.
        /// </summary>
        [JsonPropertyName("lines")]
        public TranscriptSegmentLineItem[] Lines { get; set; }

        /// <summary>
        /// The speaker identifier.
        /// </summary>
        [JsonPropertyName("speaker")]
        public string Speaker { get; set; }

        /// <summary>
        /// The relative URI of the text track that the segment comes from.
        /// </summary>
        [JsonPropertyName("text_track_uri")]
        public string TextTrackUri { get; set; }

        /// <summary>
        /// The translation metadata of the segment.
        /// </summary>
        [JsonPropertyName("translation_metadata")]
        public TranscriptSegmentTranslationMetadata TranslationMetadata { get; set; }

        /// <summary>
        /// The canonical relative URI of the segment's video.
        /// </summary>
        [JsonPropertyName("video_uri")]
        public string VideoUri { get; set; }

        /// <summary>
        /// The word data for the segment.
        /// </summary>
        [JsonPropertyName("words")]
        public TranscriptSegmentWordItem[] Words { get; set; }

        /// <summary>
        /// The fields of the response not mapped by the library.
        /// </summary>
        [JsonExtensionData]
        public Dictionary<string, JsonElement> AdditionalData { get; set; }
    }

    /// <summary>
    /// Segment Words
    /// </summary>
    public class TranscriptSegmentWordItem
    {
        /// <summary>
        /// The end time of the word in milliseconds.
        /// </summary>
        [JsonPropertyName("end_time")]
        public double? EndTime { get; set; }

        /// <summary>
        /// The start time of the word in milliseconds.
        /// </summary>
        [JsonPropertyName("start_time")]
        public double? StartTime { get; set; }

        /// <summary>
        /// The word text.
        /// </summary>
        [JsonPropertyName("word")]
        public string Word { get; set; }
    }

    /// <summary>
    /// Segment Translation Metadata
    /// </summary>
    public class TranscriptSegmentTranslationMetadata
    {
        /// <summary>
        /// Whether the audio of the translation's segment is out of sync.
        /// </summary>
        [JsonPropertyName("audio_out_of_sync")]
        public bool? AudioOutOfSync { get; set; }

        /// <summary>
        /// The ID of the translation's audio track.
        /// </summary>
        [JsonPropertyName("audio_track_id")]
        public string AudioTrackId { get; set; }

        /// <summary>
        /// The translation language in ISO 639-1 format.
        /// </summary>
        [JsonPropertyName("dominant_language")]
        public string DominantLanguage { get; set; }

        /// <summary>
        /// The vendor ID of the translation's dubbing.
        /// </summary>
        [JsonPropertyName("dubbing_id")]
        public string DubbingId { get; set; }

        /// <summary>
        /// The vendor ID of the translation's segment.
        /// </summary>
        [JsonPropertyName("dubbing_segment_id")]
        public string DubbingSegmentId { get; set; }

        /// <summary>
        /// Whether the translation's segment is out of sync.
        /// </summary>
        [JsonPropertyName("translation_out_of_sync")]
        public bool? TranslationOutOfSync { get; set; }
    }

    /// <summary>
    /// Segment Line
    /// </summary>
    public class TranscriptSegmentLineItem
    {
        /// <summary>
        /// The text from the segment line.
        /// </summary>
        [JsonPropertyName("text")]
        public string Text { get; set; }

        /// <summary>
        /// The speaker of the segment line.
        /// </summary>
        [JsonPropertyName("voice")]
        public string Voice { get; set; }
    }
}
